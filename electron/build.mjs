/**
 * 打包脚本：把后端 + 前端 + Electron 主进程合成可分发目录。
 *
 *   node electron/build.mjs            只构建（出 dist-electron/）
 *   node electron/build.mjs --pack     构建后调用 electron-builder 出 exe
 *
 * 后端用 esbuild 打成单文件 CJS：这样用户机器上不需要 node_modules，
 * 也不会有原生模块路径问题（node:sqlite 是 Node 内置的，正好不用编译）。
 */
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const out = path.join(root, 'dist-electron')
const pack = process.argv.includes('--pack')

function log(msg) {
  console.log(`[build] ${msg}`)
}

function sizeOf(dir) {
  let total = 0
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name)
      if (e.isDirectory()) walk(p)
      else if (e.isFile()) {
        try {
          total += fs.statSync(p).size
        } catch {
          /* ignore */
        }
      }
    }
  }
  try {
    walk(dir)
  } catch {
    /* ignore */
  }
  return total
}

fs.rmSync(out, { recursive: true, force: true })
fs.mkdirSync(out, { recursive: true })

/* 1. 前端 */
log('构建前端…')
execFileSync('pnpm', ['--filter', '@alp/web', 'build'], { cwd: root, stdio: 'inherit', shell: true })
const webDist = path.join(root, 'apps', 'web', 'dist')
if (!fs.existsSync(webDist)) throw new Error('前端构建产物不存在')
fs.cpSync(webDist, path.join(out, 'web'), { recursive: true })
log(`前端 → ${path.join(out, 'web')}`)

/* 2. 后端（单文件 CJS） */
log('打包后端…')
await build({
  entryPoints: [path.join(root, 'apps', 'server', 'src', 'index.ts')],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  outfile: path.join(out, 'server.cjs'),
  // 这些要么是 Node 内置，要么带原生二进制，不能打进 bundle
  external: ['node:sqlite', 'sqlite-vec', '@huggingface/transformers', 'onnxruntime-node', 'sharp'],
  banner: {
    js: '/* ALP server bundle — generated by electron/build.mjs */',
  },
  logLevel: 'warning',
})

/* 3. 原生依赖：按真实路径解析后拷过去（pnpm 的 node_modules 全是符号链接） */
const vendorDir = path.join(out, 'node_modules')
fs.mkdirSync(vendorDir, { recursive: true })

function findReal(pkg) {
  const candidates = [
    path.join(root, 'apps', 'server', 'node_modules', pkg),
    path.join(root, 'node_modules', pkg),
  ]
  for (const c of candidates) {
    if (fs.existsSync(c)) {
      try {
        return fs.realpathSync(c)
      } catch {
        return c
      }
    }
  }
  // pnpm 的 .pnpm 布局兜底
  const pnpmDir = path.join(root, 'node_modules', '.pnpm')
  if (!fs.existsSync(pnpmDir)) return null
  const prefix = pkg.replace('/', '+') + '@'
  const hit = fs.readdirSync(pnpmDir).find((d) => d.startsWith(prefix))
  if (hit) {
    const p = path.join(pnpmDir, hit, 'node_modules', pkg)
    if (fs.existsSync(p)) {
      try {
        return fs.realpathSync(p)
      } catch {
        return p
      }
    }
  }
  return null
}

log('拷贝原生依赖…')
for (const pkg of ['sqlite-vec', 'sqlite-vec-windows-x64', '@huggingface/transformers', 'onnxruntime-node']) {
  const src = findReal(pkg)
  if (!src) {
    log(`  ! 跳过 ${pkg}（没找到）`)
    continue
  }
  const dst = path.join(vendorDir, pkg)
  fs.mkdirSync(path.dirname(dst), { recursive: true })
  fs.cpSync(src, dst, { recursive: true, dereference: true })
  const sz = sizeOf(dst)
  log(`  + ${pkg} (${(sz / 1024 / 1024).toFixed(1)} MB)`)
}

/* sqlite-vec 的 .dll 单独放一份，运行时优先从这里加载（不依赖 npm 解析） */
const vecDllCandidates = []
for (const p of [
  path.join(vendorDir, 'sqlite-vec-windows-x64', 'vec0.dll'),
  path.join(root, 'node_modules', '.pnpm'),
]) {
  if (fs.existsSync(p)) vecDllCandidates.push(p)
}
const vendorDllDir = path.join(out, 'vendor')
fs.mkdirSync(vendorDllDir, { recursive: true })
let dllCopied = false
for (const cand of vecDllCandidates) {
  if (fs.statSync(cand).isFile()) {
    fs.copyFileSync(cand, path.join(vendorDllDir, 'vec0.dll'))
    dllCopied = true
    break
  }
  // 目录：递归找
  for (const f of fs.readdirSync(cand, { withFileTypes: true })) {
    if (!f.isDirectory()) continue
    const maybe = path.join(cand, f.name, 'node_modules', 'sqlite-vec-windows-x64', 'vec0.dll')
    if (fs.existsSync(maybe)) {
      fs.copyFileSync(maybe, path.join(vendorDllDir, 'vec0.dll'))
      dllCopied = true
      break
    }
  }
  if (dllCopied) break
}
log(dllCopied ? '  + vendor/vec0.dll' : '  ! vec0.dll 没找到，打包版向量检索会退化')

/* 3. Electron 主进程 */
fs.copyFileSync(path.join(__dirname, 'main.cjs'), path.join(out, 'main.cjs'))
log('主进程 → main.cjs')

/* 3.5 图标：窗口图标 + 托盘图标都从这里取（安装包图标由 builder.json 的 win.icon 指定） */
const iconPng = path.join(root, 'build', 'icon.png')
if (fs.existsSync(iconPng)) {
  fs.copyFileSync(iconPng, path.join(out, 'icon.png'))
  log('图标 → icon.png')
} else {
  log('  ! build/icon.png 不存在，先跑 python scripts/make-icon.py')
}

/* 4. package.json —— 版本号必须跟根目录一致
   这里写成别的值，Electron 的 app.getVersion() 就会报那个值，
   用户在「关于」里看到的版本和安装包名字对不上（v1.0 踩过） */
const rootPkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
fs.writeFileSync(
  path.join(out, 'package.json'),
  JSON.stringify(
    {
      name: rootPkg.name ?? 'alp',
      productName: 'Teach me',
      version: rootPkg.version,
      description: rootPkg.description ?? 'Teach me — 本地优先的 AI 私人教师',
      main: 'main.cjs',
      author: 'YG',
      license: rootPkg.license ?? 'MIT',
    },
    null,
    2,
  ),
)
log(`package.json → v${rootPkg.version}`)

log('构建完成 →', out)

/* 5. 可选：出安装包 */
if (pack) {
  log('调用 electron-builder…')
  execFileSync(
    'pnpm',
    [
      'exec',
      'electron-builder',
      '--win',
      '--config',
      path.join(root, 'electron', 'builder.json'),
    ],
    { cwd: root, stdio: 'inherit', shell: true },
  )
  log('安装包输出在 release/')
}
